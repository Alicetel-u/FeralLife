Z = 4
img = Image.new('RGB', (173 * Z, 113 * Z), (186, 164, 126))
pen = ImageDraw.Draw(img)

def R(x, y, w, h, c):
    pen.rectangle([int(x * Z), int(y * Z), int((x + w) * Z) - 1, int((y + h) * Z) - 1], fill=c)

