import {createRequire} from 'node:module';
import {readFile,mkdir} from 'node:fs/promises';
import {resolve,join} from 'node:path';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
import {createActOne,advanceActOne,answerActOne} from '../src/act-one.js';
const require=createRequire(join(process.env.FERAL_ASSET_MODULE_ROOT,'package.json'));
const {chromium}=require('playwright');
const fixture=createActOne(42,[],1,true);advanceActOne(fixture,2);answerActOne(fixture,fixture.actOne.pending.eventId,'trash');fixture.events.forEach(e=>e.read=true);
const browser=await chromium.launch({headless:true,channel:'chrome',timeout:20000});
try{
  const page=await browser.newPage({viewport:{width:1366,height:768}}),errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(s=>{if(!sessionStorage.getItem('auto-rewind-fixture')){localStorage.setItem('feral-act-one-v1',JSON.stringify(s));sessionStorage.setItem('auto-rewind-fixture','1');}},fixture);
  await page.route('http://game.local/**',async route=>{
    const p=new URL(route.request().url()).pathname;
    await route.fulfill({body:await readFile(resolve('.'+(p==='/'?'/index.html':p))),contentType:p.endsWith('.js')?'application/javascript':p.endsWith('.css')?'text/css':p.endsWith('.png')?'image/png':'text/html'});
  });
  await mkdir('docs/auto-rewind-preview',{recursive:true});
  const save=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('feral-act-one-v1')));
  const finishReply=async()=>{await page.click('[data-event-skip]');await page.click('[data-close].primary-button');};
  await page.goto('http://game.local/');await page.click('[data-game-continue]');
  await page.waitForSelector('.rewind-screen',{timeout:22000});
  assert.equal(await page.locator('[data-act-rewind]').count(),0);
  await page.waitForSelector('.clock-locked',{timeout:15000});
  assert.equal(await page.locator('.rewind-hand.hour').evaluate(el=>el.style.transform),'rotate(195deg)');
  await page.waitForFunction(()=>!document.getElementById('modal').open);
  assert.equal((await save()).hour,18.5);assert.equal((await save()).actOne.attempt,2);
  await page.screenshot({path:'docs/auto-rewind-preview/ash-restored.png'});
  await page.click('[data-act-wait]');await page.click('[data-event-skip]');
  assert.equal(await page.locator('[data-choice="trash"].previously-chosen').count(),1);
  await page.click('[data-choice="water"]');await finishReply();
  await page.click('[data-act-wait]');await page.click('[data-event-skip]');await page.click('[data-choice="turbo"]');await finishReply();
  await page.waitForSelector('.fire-cinematic');await page.click('[data-fire-finish]');await page.waitForSelector('.rewind-screen');await page.click('[data-rewind-skip]');
  await page.waitForFunction(()=>!document.getElementById('modal').open);
  assert.equal((await save()).hour,36.5);assert.deepEqual((await save()).actOne.completed,['ash']);
  await page.screenshot({path:'docs/auto-rewind-preview/dinner-restored.png'});
  await page.reload();await page.click('[data-game-continue]');await page.waitForFunction(()=>!document.getElementById('modal').open);
  await page.click('[data-act-wait]');await page.click('[data-event-skip]');assert.equal(await page.locator('[data-choice="turbo"].previously-chosen').count(),1);
  await page.click('[data-choice="coronation"]');await finishReply();await page.click('[data-act-wait]');await page.waitForSelector('[data-act-reward]');
  const standalone=await browser.newPage();standalone.on('pageerror',e=>errors.push(e.message));
  await standalone.addInitScript(s=>localStorage.setItem('feral-act-one-v1',JSON.stringify(s)),fixture);
  await standalone.goto(pathToFileURL(resolve('play.html')).href,{timeout:60000});await standalone.click('[data-game-continue]');await standalone.click('[data-fire-finish]');await standalone.click('[data-rewind-skip]');await standalone.waitForFunction(()=>!document.getElementById('modal').open);
  assert.equal(await standalone.evaluate(()=>JSON.parse(localStorage.getItem('feral-act-one-v1')).hour),18.5);
  assert.deepEqual(errors,[]);console.log('Verified fully automatic fire/clock return to 18:30, retained ash success at 12:30 dinner rewind, reload, choices, full clear and standalone.');
}finally{await browser.close();}
